const PERMISSION_ORDER: Record<Permission, number> = {
  none: 0,
  read: 1,
  manage: 2,
};

export function hasAccess(
  role: AdminRole,
  section: SECTION,
  required: Permission = "read"
): boolean {
  const actual = ACCESS_MATRIX[role][section];
  return PERMISSION_ORDER[actual] >= PERMISSION_ORDER[required];
}

export function getAccessibleSections(role: AdminRole): SECTION[] {
  return (Object.keys(ACCESS_MATRIX[role]) as SECTION[]).filter(
    (section) => ACCESS_MATRIX[role][section] !== "none"
  );
}
